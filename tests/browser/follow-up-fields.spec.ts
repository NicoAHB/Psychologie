import { readFile } from 'node:fs/promises';
import AxeBuilder from '@axe-core/playwright';
import { test, expect } from './fixtures';
import { nav, seedWorkflow, unlock, workflowData } from './workflow-fixture';
const de = JSON.parse(await readFile(new URL('../../src/locales/de.json', import.meta.url), 'utf8')) as Record<string, string>;
const uk = JSON.parse(await readFile(new URL('../../src/locales/uk.json', import.meta.url), 'utf8')) as Record<string, string>;

for (const [width, theme] of [[820, 'light'], [390, 'dark']] as const) test(`follow-up controls never overlap at ${width}px and preserve manual notes with DE/UA suggestions`, async ({ page }, info) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 1180 });
  const { data } = workflowData(); data.clients[0].followUpOn = '2027-02-15'; data.clients[0].followUpNote = 'Eigene Notiz behalten';
  const read = await seedWorkflow(page, data);
  await page.addStyleTag({ content: '*,*::before,*::after{transition:none!important;animation:none!important}' });
  await nav(page, de.settings); await page.getByLabel(de.colorScheme, { exact: true }).selectOption(theme);
  await page.getByLabel(de.fontSize, { exact: true }).selectOption('extraLarge');
  await nav(page, de.clients); await page.locator('.directory-list button').first().click();
  await page.getByRole('button', { name: de.editClient, exact: true }).click();
  const dialog = page.getByRole('dialog'), group = dialog.getByRole('group', { name: de.followUpTitle, exact: true });
  const date = group.getByLabel(de.clientFollowUpOn, { exact: true });
  const clear = group.getByRole('button', { name: de.clientFollowUpClear, exact: true });
  await expect(date).toHaveValue('2027-02-15');
  const dateBox = (await date.boundingBox())!, clearBox = (await clear.boundingBox())!;
  expect(clearBox.y).toBeGreaterThanOrEqual(dateBox.y + dateBox.height + 8);
  expect(clearBox.height).toBeGreaterThanOrEqual(44);
  expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await group.getByLabel(de.followUpReasonPick, { exact: true }).selectOption('followUpReasonPause');
  await expect(group.getByLabel(de.clientFollowUpNote, { exact: true })).toHaveValue(`Eigene Notiz behalten\n${de.followUpReasonPause}`);
  await group.screenshot({ path: `/tmp/follow-up-${width}-${theme}-${info.project.name}.png` });
  await dialog.getByRole('button', { name: 'Українська', exact: true }).click();
  const translated = dialog.getByRole('group', { name: uk.followUpTitle, exact: true });
  await translated.getByLabel(uk.followUpReasonPick, { exact: true }).selectOption('followUpReasonPause');
  await expect(translated.getByLabel(uk.clientFollowUpNote, { exact: true })).toHaveValue(`Eigene Notiz behalten\n${de.followUpReasonPause}`);
  await expect(translated.getByRole('option', { name: uk.followUpReasonPause, exact: true })).toHaveCount(1);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await translated.getByRole('button', { name: uk.clientFollowUpClear, exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(translated.getByLabel(uk.clientFollowUpOn, { exact: true })).toHaveValue('');
  await dialog.getByRole('button', { name: uk.save, exact: true }).click(); await expect(dialog).toHaveCount(0, { timeout: 15000 });
  expect((await read()).clients[0].followUpOn).toBeUndefined();
  expect((await read()).clients[0].followUpNote).toBe(`Eigene Notiz behalten\n${de.followUpReasonPause}`);
  await page.locator('.topbar').getByRole('button', { name: 'Deutsch', exact: true }).click();
  await page.getByRole('button', { name: de.lock, exact: true }).last().click(); await page.reload(); await unlock(page);
  await nav(page, de.clients); await page.locator('.directory-list button').first().click();
  await page.getByRole('button', { name: de.editClient, exact: true }).click();
  await expect(dialog.getByLabel(de.clientFollowUpNote, { exact: true })).toHaveValue(`Eigene Notiz behalten\n${de.followUpReasonPause}`);
  await expect(dialog.getByLabel(de.clientFollowUpOn, { exact: true })).toHaveValue('');
});

test('follow-up suggestions respect long notes and an empty field accepts an editable preset', async ({ page }) => {
  const { data } = workflowData(); await seedWorkflow(page, data);
  await nav(page, de.clients); await page.getByRole('button', { name: de.newClient, exact: true }).first().click();
  const dialog = page.getByRole('dialog'), note = dialog.getByLabel(de.clientFollowUpNote, { exact: true });
  const choices = dialog.getByLabel(de.followUpReasonPick, { exact: true });
  await choices.selectOption('followUpReasonReply'); await expect(note).toHaveValue(de.followUpReasonReply);
  await choices.selectOption('followUpReasonDocuments'); await expect(note).toHaveValue(de.followUpReasonDocuments);
  await note.fill('x'.repeat(500)); await choices.selectOption('followUpReasonReply');
  await expect(dialog.getByRole('alert')).toHaveText(de.followUpReasonTooLong); await expect(note).toHaveValue('x'.repeat(500));
  await note.fill('Eigener Anlass'); await expect(dialog.getByRole('alert')).toHaveCount(0);
  await choices.selectOption('followUpReasonReply'); await expect(note).toHaveValue(`Eigener Anlass\n${de.followUpReasonReply}`);
});
